import express from 'express';
import { db } from '../db/database.js';

export const sessionRouter = express.Router();

function maskSessionId(sessionId) {
  if (!sessionId || sessionId.length < 12) return sessionId;
  return `${sessionId.substring(0, 8)}...${sessionId.substring(sessionId.length - 4)}`;
}

function parseBrowser(userAgent) {
  if (!userAgent) return 'Unknown Browser';
  if (userAgent.includes('Edg/')) return 'Microsoft Edge';
  if (userAgent.includes('Chrome/')) return 'Google Chrome';
  if (userAgent.includes('Firefox/')) return 'Mozilla Firefox';
  if (userAgent.includes('Safari/') && !userAgent.includes('Chrome/')) return 'Apple Safari';
  return 'Web Browser';
}

sessionRouter.get('/me', (req, res) => {
  const { sessionId, clientIp, userAgent, lastActivity } = req.studentSession;

  // Count events generated by this specific student session
  const eventCountStmt = db.prepare(`
    SELECT COUNT(*) as count 
    FROM events 
    WHERE session_id = ? AND is_simulated = 0
  `);
  const { count: eventsGenerated } = eventCountStmt.get(sessionId);

  // Count challenge progress
  const progressStmt = db.prepare(`
    SELECT 
      SUM(CASE WHEN attack_completed = 1 AND investigation_completed = 1 THEN 1 ELSE 0 END) as completed,
      COUNT(*) as total
    FROM challenge_progress
    WHERE session_id = ?
  `);
  const progress = progressStmt.get(sessionId) || { completed: 0, total: 3 };

  // Alert counts for student
  const alertsStmt = db.prepare(`
    SELECT 
      SUM(CASE WHEN severity = 'CRITICAL' THEN 1 ELSE 0 END) as critical,
      SUM(CASE WHEN severity = 'HIGH' THEN 1 ELSE 0 END) as high
    FROM events
    WHERE (session_id = ? AND is_simulated = 0) OR is_simulated = 1
  `);
  const alertStats = alertsStmt.get(sessionId);

  res.json({
    sessionId: maskSessionId(sessionId),
    rawSessionId: sessionId,
    publicIp: clientIp,
    connectionStatus: 'ONLINE',
    browser: parseBrowser(userAgent),
    userAgent,
    lastActivity,
    eventsGenerated,
    challenges: {
      total: 3,
      completed: progress.completed || 0,
      remaining: Math.max(0, 3 - (progress.completed || 0))
    },
    metrics: {
      criticalAlerts: alertStats?.critical || 0,
      highAlerts: alertStats?.high || 0
    }
  });
});
